// Build: src/ -> index.html, one self-contained page (no dependencies; run `node tools/build.mjs` from anywhere).
// The ES modules stay modules: at start-up each becomes a Blob URL (dependencies first; the import graph has no
// cycles) with its './x.js' imports pointed at those URLs, so live bindings (`export let gl`) behave exactly as in
// src/. Each worker gets its one dependency inlined (dng.js / export.js import nothing). CSS and the icon are inlined.
// No minifying: the Adobe DNG notice at the top of dng.js / export.js must stay in the shipped code.
import fs from 'node:fs';

const root = new URL('../', import.meta.url), read = f => fs.readFileSync(new URL(`src/${f}`, root), 'utf8');
const deps = code => [...code.matchAll(/^import [^;\n]* from '\.\/([\w-]+\.js)';$/gm)].map(m => m[1]);

const order = [], seen = new Set(); // dependencies before dependents
const visit = f => { if (seen.has(f)) return; seen.add(f); deps(read(f)).forEach(visit); order.push(f); };
visit('app.js');

const worker = f => {
  const code = read(f), [dep, ...more] = deps(code);
  if (more.length || deps(read(dep)).length) throw new Error(`${f}: only one import-free dependency can be inlined`);
  return `${read(dep).replace(/^export /gm, '')}\n${code.replace(/^import .*\r?\n/gm, '')}`; // src may have CRLF line ends
};
const workers = Object.fromEntries(['worker.js', 'export-worker.js'].map(f => [f, worker(f)]));
const modules = Object.fromEntries(order.map(f => [f, read(f).replace(/new URL\('\.\/([\w-]+\.js)', import\.meta\.url\)/g,
  (m, w) => { if (!workers[w]) throw new Error(`unknown worker ${w}`); return `globalThis.__bundle.workers['${w}']`; })]));
for (const f of order) if (/import\.meta|import\(/.test(modules[f])) throw new Error(`${f}: import.meta / dynamic import left over`);

const json = v => JSON.stringify(v).replace(/<\//g, '<\\/'); // safe inside <script>
const boot = `<script type="module">
// Bundled from src/ by tools/build.mjs: each module becomes a Blob URL, imports rewritten to them, then app.js runs.
const M = ${json(modules)}, W = ${json(workers)};
const blob = code => URL.createObjectURL(new Blob([code], { type: 'text/javascript' }));
globalThis.__bundle = { workers: Object.fromEntries(Object.entries(W).map(([k, v]) => [k, blob(v)])) };
const url = {};
for (const [f, code] of Object.entries(M)) url[f] = blob(code.replace(/from '\\.\\/([\\w-]+\\.js)'/g, (m, d) => \`from '\${url[d]}'\`));
import(url['app.js']);
</script>`;

const icon = `data:image/svg+xml,${encodeURIComponent(read('favicon.svg'))}`;
let html = read('index.html');
const swap = (a, b) => { if (!html.includes(a)) throw new Error(`index.html: ${a} not found`); html = html.split(a).join(b); };
swap('<link rel="stylesheet" href="styles.css">', `<style>\n${read('styles.css')}</style>`);
swap('src="favicon.svg"', `src="${icon}"`);
swap('href="favicon.svg"', `href="${icon}"`);
swap('<script type="module" src="app.js"></script>', boot);
html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<!-- Generated by tools/build.mjs from src/; edit src/ and rebuild. -->');
fs.writeFileSync(new URL('index.html', root), html);
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB, modules ${order.join(' ')}`);
